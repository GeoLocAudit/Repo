"""Example table for the paper (paper/examples.tex): the first three businesses recommended in BOTH twin
answers, for one question per engine and several places.

  ChatGPT, declared location (E1, question as typed): "credit unions in my area"
  Gemini, network location (E2): "which store has the cheapest groceries"

  python scripts/make_examples.py
"""
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from extract_recs import norm  # noqa: E402
from geoaudit.common import DATA, RESULTS, ROOT  # noqa: E402

EXAMPLES = [
    ('ChatGPT, declared', 'exp_02_01', 'e1_natural', 'loc_id',
     [('nyc', 'New York'), ('boi', 'Boise'), ('mia', 'Miami'), ('lon', 'London')]),
    ('Gemini, network', 'imp_06_09', None, 'run',
     [('net_ca1', 'Canada'), ('net_us_east', 'US East'), ('net_us_west', 'US West'), ('net_uk', 'UK'),
      ('net_au', 'Australia')]),
]
ABBREV = [(' Federal Credit Union', ' FCU'), (' Credit Union', ' CU')]


def short(name):
    for a, b in ABBREV:
        name = name.replace(a, b)
    return name.replace('’', "'").replace('&', r'\&')


def key(name):
    """Matching key: abbreviations unified, bracketed suffixes such as "(ICCU)" dropped."""
    s = re.sub(r'\([^)]*\)', ' ', name)
    for a, b in ABBREV:
        s = s.replace(a, b)
    return norm(s)


def stable_names(d, n=3):
    """Names (local, chain, product) in both repeats, in the order of the first repeat."""
    reps = {r.rep: [x['name'] for x in r['items'] if x['type'] in ('local', 'chain', 'product')]
            for _, r in d.iterrows()}
    if 1 not in reps or 2 not in reps:
        return []
    second = {key(x) for x in reps[2]}
    out, seen = [], set()
    for x in reps[1]:
        k = key(x)
        if k in second and k not in seen:
            out.append(short(re.sub(r'\s*\([^)]*\)', '', x)))
            seen.add(k)
    return out[:n]


QUERY_EXAMPLES = [
    ('ChatGPT, declared', 'exp_02_01', 'openai/e1_natural', [('boi', 'Boise'), ('nyc', 'New York'), ('lon', 'London')]),
    ('Gemini, network', 'imp_06_09', 'gemini', [('net_ca1', 'Canada'), ('net_us_east', 'US'), ('net_uk', 'UK'),
                                               ('net_au', 'Australia')]),
]


def query_examples():
    """paper/query_examples.tex: one search query (first repeat) per place for the two example questions;
    for each place, the first query that names a place (else the first query)."""
    import json
    q = pd.read_csv(DATA / 'questions.csv').set_index('qid')
    rows = []
    for label, qid, src, places in QUERY_EXAMPLES:
        rows.append(f'\\multicolumn{{2}}{{@{{}}l}}{{\\textit{{{label}: ``{q.at[qid, "question"]}\'\'}}}} \\\\')
        for key, name in places:
            if src.startswith('gemini'):
                f = ROOT / 'data' / 'raw' / 'gemini' / key / f'{qid}__none__r1.json'
            else:
                f = ROOT / 'data' / 'raw' / src / f'{qid}__{key}__r1.json'
            qs = json.loads(f.read_text(encoding='utf-8'))['queries']
            words = [w for w in (name, 'US', 'Canada', 'UK', 'Australia', 'Idaho', 'New York', 'London')]
            pick = next((x for x in qs if any(w in x for w in words)), qs[0] if qs else '')
            pick = re.sub(r'([&%$#_{}])', r'\\\1', pick)
            rows.append(f"\\quad {name} & ``{pick}'' \\\\")
        rows.append('\\addlinespace')
    body = '\n'.join(rows[:-1])
    (ROOT / 'paper' / 'query_examples.tex').write_text(
        '%% generated by scripts/make_examples.py - do not edit\n'
        '\\begin{tabular}{@{}lp{5.9cm}@{}}\n\\toprule\n' + body + '\n\\bottomrule\n\\end{tabular}\n', encoding='utf-8')
    print(body)


def main():
    query_examples()
    q = pd.read_csv(DATA / 'questions.csv').set_index('qid')
    d = pd.read_json(RESULTS / 'recs_all.jsonl', lines=True)
    rows = []
    for engine_label, qid, run, place, places in EXAMPLES:
        sub = d[d.qid == qid]
        sub = sub[sub.run == run] if run else sub[(sub.engine == 'gemini') & sub.run.str.startswith('net_')]
        rows.append(f'\\multicolumn{{2}}{{@{{}}l}}{{\\textit{{{engine_label}: ``{q.at[qid, "question"]}\'\'}}}} \\\\')
        for key, label in places:
            names = stable_names(sub[sub[place] == key])
            rows.append(f'\\quad {label} & {", ".join(names)} \\\\')
        rows.append('\\addlinespace')
    body = '\n'.join(rows[:-1])
    (ROOT / 'paper' / 'examples.tex').write_text(
        '%% generated by scripts/make_examples.py - do not edit\n'
        '\\begin{tabular}{@{}lp{5.6cm}@{}}\n\\toprule\n' + body + '\n\\bottomrule\n\\end{tabular}\n', encoding='utf-8')
    print(body)


if __name__ == '__main__':
    main()
